def render() -> str:
    """The sample file's exact text."""
    out = ExtractorOutput(
        device=DeviceMeta(
            device_id="11111111-2222-4333-8444-555555555555",
            client_version=CLIENT_VERSION,
            extracted_at_ms=1748102400000,
            window_days=30,
            schema_version=SCHEMA_VERSION,
        ),
        config=ConfigCounts(
            mcp_servers=9,
            hooks=2,
            custom_commands=1,
            global_claude_md_lines=142,
            global_agents_md_lines=0,
            project_claude_md_lines_avg=270,
            plugin_count=5,
        ),
        sessions=tuple(SESSIONS),
    ).to_dict()

    assert out["session_chain"] == compute_session_chain(out["sessions"])

    sessions = []
    for s in out["sessions"]:
        if s["session_hash"] in REFERENCE_SESSIONS:
            sessions.append({"ref": True, "session_hash": s["session_hash"], "digest": s["digest"]})
        else:
            sessions.append({"_comment": SESSION_COMMENTS[s["session_hash"]], **s})

    doc = {
        "_comment": TOP_COMMENT,
        "device": out["device"],
        "config": out["config"],
        "sessions": sessions,
        "session_chain": out["session_chain"],
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = SAMPLE_PATH.read_text(encoding="utf-8") if SAMPLE_PATH.exists() else ""
        if current != text:
            print(f"{SAMPLE_PATH.name} is stale — run: python tools/gen_wire_format_sample.py", file=sys.stderr)
            return 1
        print(f"{SAMPLE_PATH.name} is up to date")
        return 0
    SAMPLE_PATH.write_text(text, encoding="utf-8")
    print(f"wrote {SAMPLE_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
